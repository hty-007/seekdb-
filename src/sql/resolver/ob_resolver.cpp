// An ai column keeps its companion columns as <name>__ai_state / <name>__ai_request /
// <name>__ai_result_spec while the result column itself is user visible, so the
// presence of the state column identifies an ai result column.
static const char *AI_COLUMN_STATE_SUFFIX = "__ai_state";

static int ai_column_has_unfinished_rows(ObSchemaChecker &schema_checker,
                                         const ObTableSchema &table_schema,
                                         const ObColumnSchemaV2 &column,
                                         bool &unfinished_rows)
{
  int ret = OB_SUCCESS;
  unfinished_rows = false;
  const ObString &column_name = column.get_column_name_str();
  char state_name_buf[OB_MAX_COLUMN_NAME_LENGTH + 1];
  MEMSET(state_name_buf, 0, sizeof(state_name_buf));
  const int64_t state_name_len = snprintf(state_name_buf, sizeof(state_name_buf), "%.*s%s",
                                          column_name.length(), column_name.ptr(),
                                          AI_COLUMN_STATE_SUFFIX);
  const ObDatabaseSchema *database_schema = NULL;
  if (state_name_len <= 0 || state_name_len > OB_MAX_COLUMN_NAME_LENGTH) {
    ret = OB_ERR_UNEXPECTED;
    LOG_WARN("ai column state name is too long", K(ret), K(state_name_len));
  } else if (NULL == table_schema.get_column_schema(
                     ObString(static_cast<int32_t>(state_name_len), state_name_buf))) {
    // an ordinary column, nothing to check
  } else if (OB_FAIL(schema_checker.get_database_schema(table_schema.get_database_id(),
                                                        database_schema))) {
    LOG_WARN("failed to get database schema", K(ret));
  } else if (OB_ISNULL(database_schema)) {
    ret = OB_ERR_UNEXPECTED;
  } else {
    const ObString &database_name = database_schema->get_database_name_str();
    const ObString &table_name = table_schema.get_table_name_str();
    ObSqlString sql;
    ObISQLClient::ReadResult read_result;
    if (OB_FAIL(sql.append_fmt("select 1 from `%.*s`.`%.*s` where `%.*s` is null limit 1",
                               database_name.length(), database_name.ptr(),
                               table_name.length(), table_name.ptr(),
                               column_name.length(), column_name.ptr()))) {
      LOG_WARN("failed to build the ai column readiness query", K(ret));
    } else if (OB_FAIL(GCTX.sql_proxy_->read(read_result, sql.ptr()))) {
      LOG_WARN("failed to read the ai column readiness", K(ret), K(sql));
    } else {
      sqlclient::ObMySQLResult *result = read_result.get_result();
      if (OB_ISNULL(result)) {
        ret = OB_ERR_UNEXPECTED;
      } else {
        const int next_ret = result->next();
        if (OB_ITER_END == next_ret) {
          unfinished_rows = false;
        } else if (OB_SUCCESS == next_ret) {
          unfinished_rows = true;
        } else {
          ret = next_ret;
          LOG_WARN("failed to fetch the ai column readiness", K(ret));
        }
      }
    }
  }
  return ret;
}

static int gather_dml_stmts(ObDMLStmt *stmt, ObIArray<ObDMLStmt *> &stmts, int64_t depth)
{
  int ret = OB_SUCCESS;
  ObSEArray<ObSelectStmt *, 8> subquery_stmts;
  if (OB_ISNULL(stmt) || depth > 16) {
    ret = OB_ERR_UNEXPECTED;
  } else if (OB_FAIL(stmts.push_back(stmt))) {
  } else if (OB_FAIL(stmt->get_subquery_stmts(subquery_stmts))) {
  } else {
    for (int64_t i = 0; OB_SUCC(ret) && i < subquery_stmts.count(); ++i) {
      if (OB_ISNULL(subquery_stmts.at(i))) {
        // nothing
      } else if (OB_FAIL(gather_dml_stmts(subquery_stmts.at(i), stmts, depth + 1))) {
      }
    }
  }
  return ret;
}

// Strict read: when ai_column_strict_read is on, a statement that references an ai
// column fails as long as that column still has rows without a result. The check is
// column wide: the rows the statement actually selects do not matter.
static int check_ai_column_strict_read(ObResolverParams &params, ObStmt *stmt)
{
  int ret = OB_SUCCESS;
  ObSQLSessionInfo *session_info = params.session_info_;
  ObSchemaChecker *schema_checker = params.schema_checker_;
  ObDMLStmt *dml_stmt = NULL;
  ObObj strict_read_obj;
  int64_t strict_read = 0;
  if (OB_ISNULL(session_info) || OB_ISNULL(schema_checker) || OB_ISNULL(stmt)) {
    ret = OB_ERR_UNEXPECTED;
    LOG_WARN("resolver params are not ready", K(ret));
  } else if (OB_FAIL(session_info->get_sys_variable(SYS_VAR_AI_COLUMN_STRICT_READ,
                                                    strict_read_obj))) {
    LOG_WARN("failed to get ai_column_strict_read", K(ret));
  } else if (FALSE_IT(strict_read = strict_read_obj.get_int())) {
  } else if (0 == strict_read || !stmt->is_dml_stmt()) {
    // strict read is off, or the statement cannot reference a table column
  } else if (OB_ISNULL(dml_stmt = static_cast<ObDMLStmt *>(stmt))) {
    ret = OB_ERR_UNEXPECTED;
  } else {
    ObSEArray<ObDMLStmt *, 8> dml_stmts;
    ObSEArray<uint64_t, 32> checked_columns;
    if (OB_FAIL(gather_dml_stmts(dml_stmt, dml_stmts, 0))) {
      LOG_WARN("failed to gather the statements", K(ret));
    }
    for (int64_t i = 0; OB_SUCC(ret) && i < dml_stmts.count(); ++i) {
      ObDMLStmt *cur_stmt = dml_stmts.at(i);
      for (int64_t j = 0; OB_SUCC(ret) && j < cur_stmt->get_column_size(); ++j) {
        const ColumnItem *column_item = cur_stmt->get_column_item(j);
        ObColumnRefRawExpr *column_expr = (NULL == column_item) ? NULL : column_item->expr_;
        if (OB_ISNULL(column_expr)) {
          continue;
        }
        const uint64_t ref_table_id = (NULL == column_item) ? OB_INVALID_ID
                                                            : column_item->base_tid_;
        const uint64_t column_id = (NULL == column_item) ? OB_INVALID_ID
                                                         : column_item->base_cid_;
        bool checked = false;
        for (int64_t k = 0; !checked && k + 1 < checked_columns.count(); k += 2) {
          checked = checked_columns.at(k) == ref_table_id
                    && checked_columns.at(k + 1) == column_id;
        }
        if (checked || OB_INVALID_ID == ref_table_id || OB_INVALID_ID == column_id) {
          continue;
        }
        const ObTableSchema *table_schema = NULL;
        const ObColumnSchemaV2 *column_schema = NULL;
        bool unfinished_rows = false;
        if (OB_FAIL(schema_checker->get_table_schema(ref_table_id, table_schema))) {
          LOG_WARN("failed to get table schema", K(ret), K(ref_table_id));
        } else if (OB_ISNULL(table_schema)) {
          ret = OB_ERR_UNEXPECTED;
        } else if (OB_ISNULL(column_schema = table_schema->get_column_schema(column_id))) {
          // pseudo column, nothing to check
        } else if (OB_FAIL(checked_columns.push_back(ref_table_id))) {
        } else if (OB_FAIL(checked_columns.push_back(column_id))) {
        } else if (OB_FAIL(ai_column_has_unfinished_rows(*schema_checker, *table_schema,
                                                         *column_schema, unfinished_rows))) {
          LOG_WARN("failed to check the ai column readiness", K(ret));
        } else if (unfinished_rows) {
          LOG_USER_ERROR(OB_AI_COLUMN_NOT_READY,
                         static_cast<int64_t>(ref_table_id),
                         static_cast<int64_t>(column_id));
          ret = OB_AI_COLUMN_NOT_READY;
          LOG_WARN("ai column has unfinished tasks", K(ret), K(ref_table_id), K(column_id));
        }
      }
    }
  }
  return ret;
}

